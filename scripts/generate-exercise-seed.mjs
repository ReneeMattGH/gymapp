// Generates supabase/migrations/0003_seed_exercises.sql from src/data/exercises.json.
// Run with: npm run seed:exercises
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/data/exercises.json');
const target = join(root, 'supabase/migrations/0003_seed_exercises.sql');

const exercises = JSON.parse(readFileSync(source, 'utf8'));

const text = (value) => `'${String(value).replaceAll("'", "''")}'`;
const textArray = (values) =>
  values.length === 0 ? `'{}'::text[]` : `array[${values.map(text).join(', ')}]::text[]`;

const ids = new Set();
for (const exercise of exercises) {
  if (ids.has(exercise.id)) throw new Error(`Duplicate exercise id: ${exercise.id}`);
  ids.add(exercise.id);
}

const missing = new Set();
for (const exercise of exercises) {
  for (const alternative of exercise.alternatives ?? []) {
    if (!ids.has(alternative)) missing.add(`${exercise.id} -> ${alternative}`);
  }
}
if (missing.size > 0) {
  console.warn(`Warning: ${missing.size} alternative id(s) are not in the catalog:\n  ${[...missing].join('\n  ')}`);
}

const rows = exercises.map((exercise) =>
  [
    `  (${[
      text(exercise.id),
      text(exercise.name),
      text(exercise.category),
      textArray(exercise.primaryMuscles ?? []),
      textArray(exercise.secondaryMuscles ?? []),
      textArray(exercise.equipment ?? []),
      text(exercise.difficulty),
      textArray(exercise.instructions ?? []),
      textArray(exercise.cues ?? []),
      textArray(exercise.mistakes ?? []),
      textArray(exercise.alternatives ?? []),
      exercise.isUnilateral ? 'true' : 'false',
    ].join(', ')})`,
  ].join(''),
);

const columns = [
  'id',
  'name',
  'category',
  'primary_muscles',
  'secondary_muscles',
  'equipment',
  'difficulty',
  'instructions',
  'cues',
  'mistakes',
  'alternatives',
  'is_unilateral',
];

const assignments = columns
  .slice(1)
  .map((column) => `${column} = excluded.${column}`)
  .join(',\n  ');

const sql = `-- Generated by scripts/generate-exercise-seed.mjs from src/data/exercises.json.
-- Do not edit by hand; run: npm run seed:exercises
-- ${exercises.length} exercises.

insert into public.exercise_library (${columns.join(', ')})
values
${rows.join(',\n')}
on conflict (id) do update set
  ${assignments};
`;

mkdirSync(join(root, 'supabase/migrations'), { recursive: true });
writeFileSync(target, sql);
console.log(`Wrote ${exercises.length} exercises to ${target}`);
